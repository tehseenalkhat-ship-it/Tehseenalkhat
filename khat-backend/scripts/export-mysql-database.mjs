import 'dotenv/config';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import mysql from 'mysql2/promise';

const required = name => {
  const value = process.env[name]?.trim();
  if (!value) throw new Error(`Missing ${name} in khat-backend/.env.`);
  return value;
};

const connection = await mysql.createConnection({
  host: required('DB_HOST'),
  port: Number(process.env.DB_PORT ?? 3306),
  database: required('DB_NAME'),
  user: required('DB_USER'),
  password: required('DB_PASSWORD'),
  ...(process.env.DB_SSL_CA?.trim()
    ? { ssl: { ca: await (await import('node:fs/promises')).readFile(process.env.DB_SSL_CA.trim()), rejectUnauthorized: true } }
    : {}),
  connectTimeout: 15_000,
  timezone: 'Z',
  dateStrings: false,
});

const quoteIdentifier = value => `\`${String(value).replaceAll('`', '``')}\``;
const literal = value => {
  if (value === null || value === undefined) return 'NULL';
  if (Buffer.isBuffer(value)) return `X'${value.toString('hex')}'`;
  if (value instanceof Date) {
    const iso = value.toISOString().replace('T', ' ').replace('Z', '');
    return `'${iso.replaceAll("'", "''")}'`;
  }
  if (typeof value === 'number' || typeof value === 'bigint') return String(value);
  if (typeof value === 'boolean') return value ? '1' : '0';
  const text = typeof value === 'object' ? JSON.stringify(value) : String(value);
  return `'${text
    .replaceAll('\\', '\\\\')
    .replaceAll('\0', '\\0')
    .replaceAll('\n', '\\n')
    .replaceAll('\r', '\\r')
    .replaceAll('\t', '\\t')
    .replaceAll('\b', '\\b')
    .replaceAll(String.fromCharCode(26), '\\Z')
    .replaceAll("'", "\\'")}'`;
};

const chunks = [
  '-- Full MySQL-compatible schema and data export from the configured database.',
  `-- Source database: ${String(process.env.DB_NAME).replace(/[\r\n]/g, '')}`,
  '-- Generated by khat-backend/scripts/export-mysql-database.mjs.',
  '-- Import into a newly created/selected database; this file does not create the database or users.',
  'SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;',
  'SET FOREIGN_KEY_CHECKS = 0;',
  'SET UNIQUE_CHECKS = 0;',
  '',
];

try {
  const [tableRows] = await connection.query('SHOW FULL TABLES');
  const tableNameKey = Object.keys(tableRows[0] ?? {}).find(key => key.startsWith('Tables_in_'));
  const tableTypeKey = Object.keys(tableRows[0] ?? {}).find(key => key === 'Table_type');
  if (!tableNameKey || !tableTypeKey) throw new Error('Could not enumerate source database tables.');

  const tables = tableRows.filter(row => row[tableTypeKey] === 'BASE TABLE').map(row => row[tableNameKey]);
  const views = tableRows.filter(row => row[tableTypeKey] === 'VIEW').map(row => row[tableNameKey]);
  let exportedRows = 0;

  for (const table of tables) {
    const quotedTable = quoteIdentifier(table);
    const [createRows] = await connection.query(`SHOW CREATE TABLE ${quotedTable}`);
    const createSql = createRows[0]?.['Create Table'];
    if (typeof createSql !== 'string') throw new Error(`Could not read CREATE TABLE for ${table}.`);
    chunks.push(`DROP TABLE IF EXISTS ${quotedTable};`, `${createSql};`, '');

    const [columns] = await connection.query(`SHOW COLUMNS FROM ${quotedTable}`);
    const writableColumns = columns
      // Skip only computed columns. Columns with an automatic default such as `id ... DEFAULT (uuid())`
      // show up as DEFAULT_GENERATED and must be exported, or every row gets a new id on import.
      .filter(column => !/\b(VIRTUAL|STORED) GENERATED\b/i.test(String(column.Extra ?? '')))
      .map(column => column.Field);
    if (!writableColumns.length) continue;

    const columnList = writableColumns.map(quoteIdentifier).join(', ');
    const [rows] = await connection.query(`SELECT ${columnList} FROM ${quotedTable}`);
    exportedRows += rows.length;
    for (const row of rows) {
      const values = writableColumns.map(column => literal(row[column])).join(', ');
      chunks.push(`INSERT INTO ${quotedTable} (${columnList}) VALUES (${values});`);
    }
    chunks.push('');
  }

  for (const view of views) {
    const quotedView = quoteIdentifier(view);
    const [createRows] = await connection.query(`SHOW CREATE VIEW ${quotedView}`);
    let createSql = createRows[0]?.['Create View'];
    if (typeof createSql !== 'string') throw new Error(`Could not read CREATE VIEW for ${view}.`);
    createSql = createSql.replace(/\sDEFINER=`[^`]*`@`[^`]*`/gi, '').replace(/\sDEFINER=`[^`]*`@'[^']*'/gi, '');
    chunks.push(`DROP VIEW IF EXISTS ${quotedView};`, `${createSql};`, '');
  }

  chunks.push('SET UNIQUE_CHECKS = 1;', 'SET FOREIGN_KEY_CHECKS = 1;', '');
  const outputPath = path.resolve(process.cwd(), '..', 'tehseen_ul_khat.mysql.sql');
  await writeFile(outputPath, `${chunks.join('\n')}\n`, { encoding: 'utf8', mode: 0o600 });
  console.log(`Exported ${tables.length} tables, ${views.length} views, and ${exportedRows} rows to ${outputPath}`);
} finally {
  await connection.end();
}
